-- test_result: one row per test step per test record.
-- record_id FKs to test_record.id. test_id FKs to test_definition.id.
-- parameter/specification/spec_* are denormalized snapshots at record creation.
-- pass_fail: TRUE = PASS, FALSE = FAIL, NULL = not yet evaluated.

DROP TABLE IF EXISTS test_result CASCADE;

CREATE TABLE test_result (
  id             INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id      INTEGER      NOT NULL,             -- FK to test_record.id.
  test_id        INTEGER      NOT NULL,             -- FK to test_definition.id.
  pass_fail      BOOLEAN,                            -- TRUE = PASS, FALSE = FAIL, NULL = not evaluated.
  result         VARCHAR(255),
  comment        VARCHAR(255),
  parameter      VARCHAR(255),
  specification  VARCHAR(255),
  spec_units     VARCHAR(255),
  spec_min       VARCHAR(255),
  spec_nom       VARCHAR(255),
  spec_max       VARCHAR(255),
  pf_type        VARCHAR(255),                      -- Snapshot of test_definition.pf_type.
  format         VARCHAR(255),                      -- Snapshot of test_definition.format.
  type           INTEGER NOT NULL DEFAULT 0,        -- Snapshot of test_definition.type.
  hide_formula   VARCHAR(255),                      -- Snapshot of test_definition.hide_formula.
  default_result VARCHAR(255),                      -- Snapshot of test_definition.default_result.
  updated_at     TIMESTAMP
);

