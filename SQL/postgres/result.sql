-- result: one row per test step per test record.
-- record_id FKs to form_record.id. form_row_id FKs to form_row.id.
-- parameter/specification/spec_* are denormalized snapshots at record creation.
-- pass_fail: TRUE = PASS, FALSE = FAIL, NULL = not yet evaluated.

DROP TABLE IF EXISTS result CASCADE;

CREATE TABLE result (
  id             INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id      INTEGER      NOT NULL,             -- FK to form_record.id.
  form_row_id    INTEGER      NOT NULL,             -- FK to form_row.id.
  pass_fail      BOOLEAN,                            -- TRUE = PASS, FALSE = FAIL, NULL = not evaluated.
  result         VARCHAR(255),
  comment        VARCHAR(255),
  parameter      VARCHAR(255),
  specification  VARCHAR(255),
  spec_units     VARCHAR(255),
  spec_min       VARCHAR(255),
  spec_nom       VARCHAR(255),
  spec_max       VARCHAR(255),
  pf_type        VARCHAR(255),                      -- Snapshot of form_row.pf_type.
  format         VARCHAR(255),                      -- Snapshot of form_row.format.
  type           INTEGER NOT NULL DEFAULT 0,        -- Snapshot of form_row.type.
  hide_formula   VARCHAR(255),                      -- Snapshot of form_row.hide_formula.
  default_result VARCHAR(255),                      -- Snapshot of form_row.default_result.
  updated_at     TIMESTAMP
);

