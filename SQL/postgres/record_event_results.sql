-- record_event_results: per-lock result snapshot (#251). One row per data result,
-- captured when a record is completed, linked to the 'completed' record_events row.
-- Never updated after insert.

DROP TABLE IF EXISTS record_event_results CASCADE;

CREATE TABLE record_event_results (
  id            INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id      INTEGER      NOT NULL REFERENCES record_events (id),  -- the 'completed' event.
  form_row_id   INTEGER      NOT NULL,    -- FK to form_row.id.
  parameter     VARCHAR(255),
  specification VARCHAR(255),
  spec_units    VARCHAR(255),
  result        VARCHAR(255),
  pass_fail     BOOLEAN,                   -- TRUE = PASS, FALSE = FAIL, NULL = not evaluated.
  comment       VARCHAR(255)
);
